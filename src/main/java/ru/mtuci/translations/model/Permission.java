package ru.mtuci.translations.model;

/** Отдельные права. Роль — это набор прав (см. {@link Role}). */
public enum Permission {
    /** Управление пользователями: список, роли, блокировка, удаление. */
    USERS_MANAGE,
    /** Создание своих проектов и сегментов, запуск / завершение / архивирование своих проектов. */
    PROJECTS_MANAGE,
    /** Создание своих переводов, отправка на согласование, устранение замечаний. */
    TRANSLATIONS_WRITE,
    /** Согласование переводов в своих проектах: утверждение, отклонение, замечания. */
    TRANSLATIONS_REVIEW
}
